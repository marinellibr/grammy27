import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, ignoreHTTPSErrors: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('https://open.spotify.com/**', route => route.fulfill({ contentType: 'text/html', body: 'Spotify preview' }));
try {
  await page.goto(process.env.BALLOT_URL || 'http://127.0.0.1:4173/grammy27/');
  await page.locator('.custom-mode-card').click();
  await page.getByRole('button', { name: 'Choose my categories', exact: true }).click();
  await page.getByRole('heading', { name: 'Set your own stage.' }).waitFor();
  assert.equal(await page.getByRole('checkbox').count(), 100);
  assert.equal(await page.getByRole('button', { name: 'Continue with 0 categories' }).isDisabled(), true);
  await page.getByRole('checkbox', { name: 'Album Of The Year', exact: true }).check();
  assert.equal(await page.getByRole('button', { name: 'Continue with 1 category' }).isDisabled(), true);
  const second = page.getByRole('checkbox', { name: 'Record Of The Year', exact: true });
  await second.focus(); await page.keyboard.press('Space');
  assert.equal(await page.getByRole('button', { name: 'Continue with 2 categories' }).isEnabled(), true);
  await page.keyboard.press('Space');
  assert.equal(await page.getByRole('button', { name: 'Continue with 1 category' }).isDisabled(), true);
  await page.keyboard.press('Space');
  await page.getByRole('searchbox', { name: 'Find a category' }).fill('rock');
  assert.ok(await page.getByRole('checkbox').count() > 0);
  assert.equal(await page.getByRole('button', { name: 'Continue with 2 categories' }).isEnabled(), true);
  await page.getByRole('searchbox').fill('no-such-category');
  await page.getByText('No categories match', { exact: false }).waitFor();
  await page.reload();
  assert.equal(await page.locator('.custom-mode-card input').isChecked(), true);
  await page.getByRole('button', { name: 'Choose my categories', exact: true }).click();
  assert.equal(await page.getByRole('checkbox', { checked: true }).count(), 2);
  await page.getByRole('button', { name: 'Select all 100' }).click();
  assert.equal(await page.getByRole('checkbox', { checked: true }).count(), 100);
  await page.getByRole('button', { name: 'Clear selection' }).click();
  assert.equal(await page.getByRole('checkbox', { checked: true }).count(), 0);
  await page.getByRole('checkbox', { name: 'Album Of The Year', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Record Of The Year', exact: true }).check();
  await mkdir('qa', { recursive: true });
  await page.screenshot({ path: 'qa/custom-mobile-light.png' });
  await page.getByRole('switch', { name: 'Dark mode' }).click();
  await page.screenshot({ path: 'qa/custom-mobile-dark.png' });
  for (const width of [320, 768, 1440]) { await page.setViewportSize({ width, height: 900 }); assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true); }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Continue with 2 categories' }).click();
  await page.getByRole('heading', { name: 'Album Of The Year', exact: true }).waitFor();
  assert.match(await page.locator('.stepper-copy').innerText(), /\/ 2/);
  await page.locator('.nominee-label').first().click();
  await page.getByRole('button', { name: 'Next category', exact: true }).click();
  await page.getByRole('heading', { name: 'Record Of The Year', exact: true }).waitFor();
  await page.locator('.nominee-label').nth(1).click();
  await page.getByRole('button', { name: 'See my picks', exact: true }).click();
  assert.equal(await page.locator('.summary-card').count(), 2);
  await page.getByRole('button', { name: 'Create my Instagram story' }).click();
  await page.locator('.story-preview').waitFor();
  await page.locator('.story-preview').evaluate(image => image.decode());
  assert.match(await page.locator('.story-pagination').innerText(), /Story 1 of 1/);
  const wait = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save image', exact: true }).click();
  const download = await wait, png = await readFile(await download.path());
  assert.equal(png.readUInt32BE(16), 1080); assert.equal(png.readUInt32BE(20), 1920);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Grammy 2027 home' }).click();
  await page.locator('.mode-card:has(input[value="full"])').click();
  await page.getByRole('button', { name: 'Continue my ballot' }).click();
  await page.getByRole('heading', { name: 'Song Of The Year', exact: true }).waitFor();
  assert.match(await page.locator('.stepper-copy').innerText(), /2 of 100 picked/);
  await page.getByRole('button', { name: 'Grammy 2027 home' }).click();
  await page.locator('.custom-mode-card').click();
  await page.getByRole('button', { name: 'Choose my categories', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Record Of The Year', exact: true }).uncheck();
  assert.equal(await page.getByRole('button', { name: 'Continue with 1 category' }).isDisabled(), true);
  await page.getByRole('checkbox', { name: 'Song Of The Year', exact: true }).check();
  await page.getByRole('button', { name: 'Continue with 2 categories' }).click();
  await page.getByRole('heading', { name: 'Song Of The Year', exact: true }).waitFor();
  await page.locator('.nominee-label').first().click();
  await page.getByRole('button', { name: 'See my picks', exact: true }).click();
  assert.equal(await page.locator('.summary-card').count(), 2);
  assert.equal(await page.locator('.summary-category').allTextContents().then(values => values.includes('Record Of The Year')), false);
  assert.deepEqual(errors, []);
  console.log('PASS: all 100 category cards, 0/1/2 minimum, keyboard selection, search, select all/clear, persistence, mobile/dark/responsive layouts, two-category voting/summary/Story, changing the subset, and shared picks with the full ballot.');
} finally { await browser.close(); }
